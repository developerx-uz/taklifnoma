let currentLang = 'uz';

function switchLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  
  // Update button active states
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  const t = translations[lang];

  // Update elements with data-key
  document.querySelectorAll('[data-key]').forEach(el => {
    const key = el.dataset.key;
    if (t[key] !== undefined) {
      if (key === 'card_message' || key === 'biz_text') {
        el.innerHTML = t[key];
      } else {
        el.textContent = t[key];
      }
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-key-ph]').forEach(el => {
    const key = el.dataset.keyPh;
    if (t[key] !== undefined) {
      el.placeholder = t[key];
    }
  });

  try {
    localStorage.setItem('wedding_lang', lang);
  } catch (_) {}
}

// Attach language selector events on load
document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      switchLanguage(btn.dataset.lang);
    });
  });

  const savedLang = localStorage.getItem('wedding_lang');
  if (savedLang && translations[savedLang]) {
    switchLanguage(savedLang);
  }
});
